-- Migración para Finanzas Multi-Unidad y Cashflow Consolidado (Ticket 41)
-- Registro consolidado de 4 unidades: nexobow, alaynow, gastos_operativos, gastos_personales

CREATE SCHEMA IF NOT EXISTS public;

-- 1. Tipos Enumerados para Unidades de Negocio, Flujo, Recurrencia y Moneda
DO $$ BEGIN
  CREATE TYPE public.business_unit_type AS ENUM (
    'nexobow',
    'alaynow',
    'gastos_operativos',
    'gastos_personales'
  );
EXCEPTION
  WHEN duplicate_object THEN null;
END $$;

DO $$ BEGIN
  CREATE TYPE public.financial_flow_type AS ENUM (
    'ingreso',
    'egreso'
  );
EXCEPTION
  WHEN duplicate_object THEN null;
END $$;

DO $$ BEGIN
  CREATE TYPE public.recurrence_type AS ENUM (
    'unico',
    'mensual',
    'anual'
  );
EXCEPTION
  WHEN duplicate_object THEN null;
END $$;

DO $$ BEGIN
  CREATE TYPE public.currency_type AS ENUM (
    'ARS',
    'USD'
  );
EXCEPTION
  WHEN duplicate_object THEN null;
END $$;

-- 2. Tabla Principal de Transacciones Financieras
CREATE TABLE IF NOT EXISTS public.financial_transactions (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  
  -- Unidad de negocio responsable
  business_unit public.business_unit_type NOT NULL,
  
  -- Sentido del flujo: ingreso o egreso
  flow_type public.financial_flow_type NOT NULL,
  
  -- Categoría del movimiento (ej. "Setup Web", "Abono Mensual", "YouTube AdSense", "Software & SaaS", etc.)
  category text NOT NULL,
  
  -- Descripción detallada
  description text NOT NULL,
  
  -- Monto en la divisa original
  amount numeric(14, 2) NOT NULL CHECK (amount >= 0),
  
  -- Divisa de la transacción (ARS o USD)
  currency public.currency_type NOT NULL DEFAULT 'ARS',
  
  -- Tipo de cambio de referencia ARS/USD al momento del registro
  exchange_rate numeric(10, 4) NOT NULL DEFAULT 1.0,
  
  -- Recurrencia para clasificar costos fijos vs variables
  recurrence public.recurrence_type NOT NULL DEFAULT 'unico',
  
  -- Fecha contable de la transacción
  transaction_date date NOT NULL DEFAULT CURRENT_DATE,
  
  -- Vínculo opcional con cliente / prospecto de NexoBow
  lead_id bigint REFERENCES public.leads(id) ON DELETE SET NULL,
  
  -- Estado contable de la transacción
  status text NOT NULL DEFAULT 'completado',
  
  -- Metadatos adicionales (comprobante, método de pago, notas)
  metadata jsonb DEFAULT '{}'::jsonb,
  
  -- Auditoría y estampas de tiempo
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- 3. Índices de Búsqueda y Agregación Financiera
CREATE INDEX IF NOT EXISTS idx_financial_transactions_business_unit ON public.financial_transactions (business_unit);
CREATE INDEX IF NOT EXISTS idx_financial_transactions_flow_type ON public.financial_transactions (flow_type);
CREATE INDEX IF NOT EXISTS idx_financial_transactions_date ON public.financial_transactions (transaction_date);
CREATE INDEX IF NOT EXISTS idx_financial_transactions_recurrence ON public.financial_transactions (recurrence);
CREATE INDEX IF NOT EXISTS idx_financial_transactions_lead_id ON public.financial_transactions (lead_id);

-- 4. Habilitar Row Level Security (RLS) Estricto
ALTER TABLE public.financial_transactions ENABLE ROW LEVEL SECURITY;

-- 5. Políticas RLS para Propietario (ADMIN_OWNER_EMAIL)
DROP POLICY IF EXISTS "Admin owner has full access to financial_transactions" ON public.financial_transactions;
CREATE POLICY "Admin owner has full access to financial_transactions"
  ON public.financial_transactions
  FOR ALL
  TO authenticated
  USING (
    public.is_admin_owner() OR (auth.jwt() ->> 'email' = coalesce(current_setting('app.admin_owner_email', true), 'juanma@nexobow.site'))
  )
  WITH CHECK (
    public.is_admin_owner() OR (auth.jwt() ->> 'email' = coalesce(current_setting('app.admin_owner_email', true), 'juanma@nexobow.site'))
  );

-- 6. Trigger para Sincronización Automática de updated_at
CREATE OR REPLACE FUNCTION public.handle_financial_transactions_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_financial_transaction_updated ON public.financial_transactions;
CREATE TRIGGER on_financial_transaction_updated
  BEFORE UPDATE ON public.financial_transactions
  FOR EACH ROW
  EXECUTE FUNCTION public.handle_financial_transactions_updated_at();
