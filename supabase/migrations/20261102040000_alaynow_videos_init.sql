-- Migración para Videos Alaynow: Pipeline Editorial de Contenido YouTube (Ticket 43)
-- Gestión y producción audiovisual, métricas post-publicación, patrocinios y RLS

CREATE SCHEMA IF NOT EXISTS public;

-- 1. Tipo Enumerado para Etapas de Producción Audiovisual (6 etapas)
DO $$ BEGIN
  CREATE TYPE public.video_production_stage AS ENUM (
    'idea',
    'guion',
    'grabacion',
    'edicion',
    'programado',
    'publicado'
  );
EXCEPTION
  WHEN duplicate_object THEN null;
END $$;

-- 2. Tabla Principal de Videos de Alaynow
CREATE TABLE IF NOT EXISTS public.alaynow_videos (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  
  -- Título del video o concepto
  title text NOT NULL,
  
  -- Descripción, gancho o síntesis temática
  description text DEFAULT '',
  
  -- Etapa del pipeline editorial
  stage public.video_production_stage NOT NULL DEFAULT 'idea',
  
  -- Fecha prevista para rodaje o publicación
  target_date date,
  
  -- Fecha real en que el video se lanzó en YouTube
  published_at timestamptz,
  
  -- Enlace a documento de guión (Google Docs, Notion, Markdown)
  script_url text DEFAULT '',
  
  -- Enlace a miniatura o mockup visual (Figma, Drive, Cloudflare)
  thumbnail_url text DEFAULT '',
  
  -- Enlace final al video publicado en YouTube (o revisión Frame.io)
  video_url text DEFAULT '',
  
  -- Datos de Patrocinio Comercial
  has_sponsor boolean NOT NULL DEFAULT false,
  sponsor_name text DEFAULT '',
  sponsor_fee numeric DEFAULT 0,
  sponsor_currency text DEFAULT 'USD',
  is_sponsor_paid boolean NOT NULL DEFAULT false,
  
  -- Métricas Post-Lanzamiento en YouTube
  views_count integer DEFAULT 0,
  ctr_percent numeric(5,2) DEFAULT 0.00,
  likes_count integer DEFAULT 0,
  comments_count integer DEFAULT 0,
  metrics_updated_at timestamptz,
  
  -- Etiquetas temáticas y notas de producción
  tags text[] DEFAULT '{}',
  notes text DEFAULT '',
  metadata jsonb DEFAULT '{}'::jsonb,
  
  -- Auditoría y estampas cronológicas
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- 3. Índices de Búsqueda y Pipeline
CREATE INDEX IF NOT EXISTS idx_alaynow_videos_stage ON public.alaynow_videos (stage);
CREATE INDEX IF NOT EXISTS idx_alaynow_videos_target_date ON public.alaynow_videos (target_date);
CREATE INDEX IF NOT EXISTS idx_alaynow_videos_has_sponsor ON public.alaynow_videos (has_sponsor);
CREATE INDEX IF NOT EXISTS idx_alaynow_videos_created_at ON public.alaynow_videos (created_at DESC);

-- 4. Habilitar Row Level Security (RLS) Estricto
ALTER TABLE public.alaynow_videos ENABLE ROW LEVEL SECURITY;

-- 5. Políticas RLS para Propietario (ADMIN_OWNER_EMAIL)
DROP POLICY IF EXISTS "Admin owner has full access to alaynow_videos" ON public.alaynow_videos;
CREATE POLICY "Admin owner has full access to alaynow_videos"
  ON public.alaynow_videos
  FOR ALL
  TO authenticated
  USING (
    public.is_admin_owner() OR (auth.jwt() ->> 'email' = coalesce(current_setting('app.admin_owner_email', true), 'juanma@nexobow.site'))
  )
  WITH CHECK (
    public.is_admin_owner() OR (auth.jwt() ->> 'email' = coalesce(current_setting('app.admin_owner_email', true), 'juanma@nexobow.site'))
  );

-- 6. Trigger para Sincronización Automática de updated_at
CREATE OR REPLACE FUNCTION public.handle_alaynow_videos_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_alaynow_video_updated ON public.alaynow_videos;
CREATE TRIGGER on_alaynow_video_updated
  BEFORE UPDATE ON public.alaynow_videos
  FOR EACH ROW
  EXECUTE FUNCTION public.handle_alaynow_videos_updated_at();
