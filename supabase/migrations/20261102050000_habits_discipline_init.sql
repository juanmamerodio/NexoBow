-- Migración para Hábitos & Disciplina: Heatmap de Consistencia y Rachas (Ticket 44)
-- Persistencia en Supabase (habits y habit_logs), 4 pilares, unicidad diaria y RLS

CREATE SCHEMA IF NOT EXISTS public;

-- 1. Tipo Enumerado para los 4 Pilares de Hábitos
DO $$ BEGIN
  CREATE TYPE public.habit_pillar AS ENUM (
    'salud',
    'foco_negocio',
    'aprendizaje',
    'personal'
  );
EXCEPTION
  WHEN duplicate_object THEN null;
END $$;

-- 2. Tabla Principal de Hábitos (Catálogo y Metas)
CREATE TABLE IF NOT EXISTS public.habits (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  
  -- Título del hábito (ej: Entrenamiento de Fuerza, Prospección B2B)
  title text NOT NULL,
  
  -- Descripción contextual, motivación o micro-regla
  description text DEFAULT '',
  
  -- Pilar estratégico
  pillar public.habit_pillar NOT NULL DEFAULT 'salud',
  
  -- Icono representativo (nombre de icono Lucide)
  icon text DEFAULT 'CheckCircle2',
  
  -- Frecuencia semanal objetivo (1 a 7 días por semana)
  target_frequency_per_week integer NOT NULL DEFAULT 7 CHECK (target_frequency_per_week >= 1 AND target_frequency_per_week <= 7),
  
  -- Color representativo en paleta Soft-Obsidian
  color_hex text DEFAULT '#BF40FA',
  
  -- Estado de archivo
  is_archived boolean NOT NULL DEFAULT false,
  
  -- Orden / posición visual
  position integer NOT NULL DEFAULT 0,
  
  -- Auditoría cronológica
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- 3. Tabla de Registros Diarios de Hábitos (Completitudes)
CREATE TABLE IF NOT EXISTS public.habit_logs (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  
  -- Relación con el hábito maestro
  habit_id bigint NOT NULL REFERENCES public.habits(id) ON DELETE CASCADE,
  
  -- Fecha de completitud (YYYY-MM-DD)
  completed_date date NOT NULL,
  
  -- Notas opcionales de la jornada (ej: "10km en 48min", "15 mensajes enviados")
  notes text DEFAULT '',
  
  -- Estampa temporal del registro
  created_at timestamptz NOT NULL DEFAULT now(),
  
  -- Restricción de unicidad: un hábito solo puede completarse una vez por día
  CONSTRAINT uq_habit_date UNIQUE (habit_id, completed_date)
);

-- 4. Índices para Búsqueda Rápida y Heatmap Anual
CREATE INDEX IF NOT EXISTS idx_habits_pillar ON public.habits (pillar);
CREATE INDEX IF NOT EXISTS idx_habits_is_archived ON public.habits (is_archived);
CREATE INDEX IF NOT EXISTS idx_habits_position ON public.habits (position);
CREATE INDEX IF NOT EXISTS idx_habit_logs_habit_id ON public.habit_logs (habit_id);
CREATE INDEX IF NOT EXISTS idx_habit_logs_completed_date ON public.habit_logs (completed_date);
CREATE INDEX IF NOT EXISTS idx_habit_logs_habit_date ON public.habit_logs (habit_id, completed_date);

-- 5. Habilitar Row Level Security (RLS) Estricto
ALTER TABLE public.habits ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.habit_logs ENABLE ROW LEVEL SECURITY;

-- 6. Políticas RLS para Propietario (ADMIN_OWNER_EMAIL)
DROP POLICY IF EXISTS "Admin owner has full access to habits" ON public.habits;
CREATE POLICY "Admin owner has full access to habits"
  ON public.habits
  FOR ALL
  TO authenticated
  USING (
    public.is_admin_owner() OR (auth.jwt() ->> 'email' = coalesce(current_setting('app.admin_owner_email', true), 'juanma@nexobow.site'))
  )
  WITH CHECK (
    public.is_admin_owner() OR (auth.jwt() ->> 'email' = coalesce(current_setting('app.admin_owner_email', true), 'juanma@nexobow.site'))
  );

DROP POLICY IF EXISTS "Admin owner has full access to habit_logs" ON public.habit_logs;
CREATE POLICY "Admin owner has full access to habit_logs"
  ON public.habit_logs
  FOR ALL
  TO authenticated
  USING (
    public.is_admin_owner() OR (auth.jwt() ->> 'email' = coalesce(current_setting('app.admin_owner_email', true), 'juanma@nexobow.site'))
  )
  WITH CHECK (
    public.is_admin_owner() OR (auth.jwt() ->> 'email' = coalesce(current_setting('app.admin_owner_email', true), 'juanma@nexobow.site'))
  );

-- 7. Trigger para Actualización Automática de updated_at en habits
CREATE OR REPLACE FUNCTION public.handle_habits_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_habit_updated ON public.habits;
CREATE TRIGGER on_habit_updated
  BEFORE UPDATE ON public.habits
  FOR EACH ROW
  EXECUTE FUNCTION public.handle_habits_updated_at();
