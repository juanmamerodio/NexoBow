-- Migración para el CRM y Prospección en Supabase (Ticket 40)
-- Sustitución de Google Sheets ('Prospección NexoBow'!B11:S1000) por tabla relacional 'leads'

CREATE SCHEMA IF NOT EXISTS public;

-- 1. Tipos Enumerados para Estados de Embudo y Respuesta
DO $$ BEGIN
  CREATE TYPE public.lead_funnel_status AS ENUM (
    '1. Prospecto Identificado',
    '2. Contactado',
    '3. Reunión Agendada',
    '4. Propuesta Enviada',
    '5. Negociación / Cierre',
    '6. Descartado'
  );
EXCEPTION
  WHEN duplicate_object THEN null;
END $$;

DO $$ BEGIN
  CREATE TYPE public.lead_response_status AS ENUM (
    'Sin Contactar',
    'Esperando Respuesta',
    'Interesado',
    'No Interesado',
    'Respondio'
  );
EXCEPTION
  WHEN duplicate_object THEN null;
END $$;

-- 2. Tabla Principal de Leads (Mapeo 1:1 de 18 Columnas + Control TTL de 7 Días)
CREATE TABLE IF NOT EXISTS public.leads (
  -- 1 (Col B). Nº / ID Correlativo Entero
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  
  -- Identificador canónico y URL de preview en preview.nexobow.site/{slug}/
  slug text UNIQUE NOT NULL,
  
  -- 2 (Col C). Prospecto / Nombre o Razón Social
  name text NOT NULL,
  
  -- 3 (Col D). Nicho / Rubro (nutricionista, psicologo, abogado, clinica, etc.)
  niche text NOT NULL DEFAULT 'nutricionista',
  
  -- 4 (Col E). Canal de Contacto (WhatsApp, Instagram, Email, etc.)
  contact_channel text NOT NULL DEFAULT 'WhatsApp',
  
  -- 5 (Col F). Enlace de WhatsApp con mensaje precargado
  whatsapp_link text,
  
  -- 6 (Col G). Web Demo URL (https://preview.nexobow.site/{slug}/)
  demo_url text,
  
  -- 7 (Col H). Perfil de Instagram o enlace social
  social_link text,
  
  -- 8 (Col I). Ubicación completa (ej. "Av. Córdoba 5869, Palermo, CABA")
  location text NOT NULL DEFAULT 'Buenos Aires',
  
  -- Ciudad o localidad filtrable (Campana, Zárate, Caballito, Belgrano, Palermo, etc.)
  city text DEFAULT 'Buenos Aires',
  
  -- 9 (Col J). Estado del Lead / Embudo
  funnel_status public.lead_funnel_status NOT NULL DEFAULT '1. Prospecto Identificado',
  
  -- 10 (Col K). Fecha de 1er Contacto
  first_contact_date date DEFAULT CURRENT_DATE,
  
  -- 11 (Col L). Fecha de Último Contacto
  last_contact_date date,
  
  -- 12 (Col M). Estado de Respuesta
  response_status public.lead_response_status NOT NULL DEFAULT 'Sin Contactar',
  
  -- 13 (Col N). ¿Reunión Agendada?
  meeting_booked boolean NOT NULL DEFAULT false,
  
  -- 14 (Col O). Fecha de Reunión
  meeting_date timestamptz,
  
  -- 15 (Col P). Valor Potencial en Pesos Argentinos
  potential_value text NOT NULL DEFAULT '$189.999 ARS',
  
  -- 16 (Col Q). Estado del Negocio
  business_status text NOT NULL DEFAULT 'En Proceso',
  
  -- 17 (Col R). Próximo Paso / Notas / Observaciones
  notes text,
  
  -- 18 (Col S). Teléfono normalizado (+549...)
  phone text,
  
  -- Metadatos del Ciclo de Vida (TTL 7 Días)
  created_at timestamptz NOT NULL DEFAULT now(),
  last_activity_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL DEFAULT (now() + interval '7 days'),
  
  -- Metadata adicional flexible (ratings, reviews, etc.)
  metadata jsonb DEFAULT '{}'::jsonb,
  
  -- Auditoría de actualización
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- 3. Índices de Búsqueda y Filtrado
CREATE INDEX IF NOT EXISTS idx_leads_funnel_status ON public.leads (funnel_status);
CREATE INDEX IF NOT EXISTS idx_leads_niche ON public.leads (niche);
CREATE INDEX IF NOT EXISTS idx_leads_city ON public.leads (city);
CREATE INDEX IF NOT EXISTS idx_leads_expires_at ON public.leads (expires_at);
CREATE INDEX IF NOT EXISTS idx_leads_phone ON public.leads (phone);
CREATE INDEX IF NOT EXISTS idx_leads_slug ON public.leads (slug);

-- 4. Habilitar Row Level Security (RLS) Estricto
ALTER TABLE public.leads ENABLE ROW LEVEL SECURITY;

-- 5. Políticas RLS para Propietario (ADMIN_OWNER_EMAIL)
DROP POLICY IF EXISTS "Admin owner has full access to leads" ON public.leads;
CREATE POLICY "Admin owner has full access to leads"
  ON public.leads
  FOR ALL
  TO authenticated
  USING (
    public.is_admin_owner() OR (auth.jwt() ->> 'email' = coalesce(current_setting('app.admin_owner_email', true), 'juanma@nexobow.site'))
  )
  WITH CHECK (
    public.is_admin_owner() OR (auth.jwt() ->> 'email' = coalesce(current_setting('app.admin_owner_email', true), 'juanma@nexobow.site'))
  );

-- 6. Trigger para Sincronización Automática de updated_at
CREATE OR REPLACE FUNCTION public.handle_leads_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_lead_updated ON public.leads;
CREATE TRIGGER on_lead_updated
  BEFORE UPDATE ON public.leads
  FOR EACH ROW
  EXECUTE FUNCTION public.handle_leads_updated_at();
