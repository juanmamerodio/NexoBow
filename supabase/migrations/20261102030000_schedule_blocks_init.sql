-- Migración para Horarios & Time-Blocking con Sincronización Calendar (Ticket 42)
-- Centro de estructuración de la semana ideal del fundador y seguimiento de bloques de foco

CREATE SCHEMA IF NOT EXISTS public;

-- 1. Tipo Enumerado para Categorías de Bloques de Foco
DO $$ BEGIN
  CREATE TYPE public.schedule_category AS ENUM (
    'prospeccion',
    'alaynow_grabacion',
    'desarrollo',
    'reunion',
    'personal'
  );
EXCEPTION
  WHEN duplicate_object THEN null;
END $$;

-- 2. Tabla Principal de Bloques de Horario y Trabajo Profundo
CREATE TABLE IF NOT EXISTS public.schedule_blocks (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  
  -- Nombre del bloque de foco
  title text NOT NULL,
  
  -- Descripción u objetivos concretos de la sesión
  description text DEFAULT '',
  
  -- Categoría del bloque (prospección, grabación, deep work, llamadas, etc.)
  category public.schedule_category NOT NULL,
  
  -- Día de la semana (1 = Lunes, 2 = Martes, ..., 7 = Domingo)
  day_of_week smallint NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),
  
  -- Horario de inicio (formato time: HH:MM:SS)
  start_time time NOT NULL,
  
  -- Horario de fin (formato time: HH:MM:SS)
  end_time time NOT NULL,
  
  -- Check de validación cronológica básica
  CONSTRAINT check_schedule_time_range CHECK (end_time > start_time),
  
  -- Conmutador de cumplimiento de la semana
  is_completed boolean NOT NULL DEFAULT false,
  
  -- Flag de recurrencia en la semana ideal
  is_recurring boolean NOT NULL DEFAULT true,
  
  -- Color representativo personalizado en hex (opcional)
  color_hex text,
  
  -- Identificador de sincronización externa con Google Calendar
  google_calendar_event_id text,
  
  -- Flag indicativo de evento externo reflejado
  is_external boolean NOT NULL DEFAULT false,
  
  -- Metadatos adicionales (enlaces de meet, notas de contexto, etiquetas)
  metadata jsonb DEFAULT '{}'::jsonb,
  
  -- Auditoría y estampas de tiempo
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- 3. Índices de Búsqueda y Grilla Semanal
CREATE INDEX IF NOT EXISTS idx_schedule_blocks_day_time ON public.schedule_blocks (day_of_week, start_time);
CREATE INDEX IF NOT EXISTS idx_schedule_blocks_category ON public.schedule_blocks (category);
CREATE INDEX IF NOT EXISTS idx_schedule_blocks_gcal_id ON public.schedule_blocks (google_calendar_event_id);
CREATE INDEX IF NOT EXISTS idx_schedule_blocks_is_completed ON public.schedule_blocks (is_completed);

-- 4. Habilitar Row Level Security (RLS) Estricto
ALTER TABLE public.schedule_blocks ENABLE ROW LEVEL SECURITY;

-- 5. Políticas RLS para Propietario (ADMIN_OWNER_EMAIL)
DROP POLICY IF EXISTS "Admin owner has full access to schedule_blocks" ON public.schedule_blocks;
CREATE POLICY "Admin owner has full access to schedule_blocks"
  ON public.schedule_blocks
  FOR ALL
  TO authenticated
  USING (
    public.is_admin_owner() OR (auth.jwt() ->> 'email' = coalesce(current_setting('app.admin_owner_email', true), 'juanma@nexobow.site'))
  )
  WITH CHECK (
    public.is_admin_owner() OR (auth.jwt() ->> 'email' = coalesce(current_setting('app.admin_owner_email', true), 'juanma@nexobow.site'))
  );

-- 6. Trigger para Sincronización Automática de updated_at
CREATE OR REPLACE FUNCTION public.handle_schedule_blocks_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_schedule_block_updated ON public.schedule_blocks;
CREATE TRIGGER on_schedule_block_updated
  BEFORE UPDATE ON public.schedule_blocks
  FOR EACH ROW
  EXECUTE FUNCTION public.handle_schedule_blocks_updated_at();
